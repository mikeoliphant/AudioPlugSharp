namespace AbiGen;

/// <summary>
/// Emits the header-only C++ layer: enum classes, struct aliases, record types, a proxy class for each
/// [ManagedApi] interface (C++ calls C#) and an abstract class + thunks for each [NativeApi] interface
/// (C# calls C++).
/// </summary>
public static class CppEmitter
{
    public static string Emit(AbiModel model)
    {
        var c = new CTypes(model);
        var w = new CodeWriter();
        w.Line($"// Generated by AbiGen from {model.ContractAssembly}. Do not edit; change the contract instead.");
        w.Line("#pragma once");
        w.Line();
        w.Line("#include \"abi.h\"");
        w.Line("#include \"../abi_support.hpp\" // hand-written: Result, NotSupported, fixed-string helpers");
        w.Line();
        w.Line("#include <algorithm>");
        w.Line("#include <cstdint>");
        w.Line("#include <cstring>");
        w.Line("#include <span>");
        w.Line("#include <string>");
        w.Line("#include <string_view>");
        w.Line("#include <vector>");
        w.Line();
        w.Line($"namespace {model.CppNamespace} {{");
        w.Line();

        foreach (var e in model.Enums) EmitEnum(w, e);
        foreach (var s in model.Structs)
        {
            if (s.IsRecord) EmitRecord(w, s, c);
            else
            {
                w.Doc(s.Doc, "cpp");
                w.Line($"using {s.Name} = {c.Name(s)};");
                w.Line();
            }
        }

        foreach (var iface in model.Interfaces)
        {
            if (iface.Direction == ApiDirection.Managed) EmitProxy(w, iface, c, model);
            else EmitNativeInterface(w, iface, c, model);
        }

        w.Line($"}} // namespace {model.CppNamespace}");
        return w.ToString();
    }

    // ---- types ------------------------------------------------------------

    private static string Cpp(TypeRef t) => t switch
    {
        PrimType { Kind: Prim.Bool } => "bool",
        PrimType p => CTypes.Prim(p.Kind),
        EnumType e => e.Def.Name,
        StructType s => s.Def.Name,
        PointerType p => Cpp(p.Element) + "*",
        ArrayType a => $"std::vector<{Cpp(a.Element)}>",
        _ => throw new InvalidOperationException($"no C++ type for {t}"),
    };

    private static void EmitEnum(CodeWriter w, EnumDef e)
    {
        var u = CTypes.Prim(e.Underlying);
        w.Doc(e.Doc, "cpp");
        w.Line($"enum class {e.Name} : {u} {{");
        w.Indent();
        foreach (var m in e.Members) w.Line($"{m.Name} = {CEmitter.Literal(m.Value, e.Underlying)},");
        w.Outdent();
        w.Line("};");
        if (e.IsFlags)
        {
            foreach (var op in new[] { "|", "&", "^" })
                w.Line($"constexpr {e.Name} operator{op}({e.Name} a, {e.Name} b) noexcept {{ return static_cast<{e.Name}>(static_cast<{u}>(a) {op} static_cast<{u}>(b)); }}");
            w.Line($"constexpr bool hasFlag({e.Name} value, {e.Name} flag) noexcept {{ return (static_cast<{u}>(value) & static_cast<{u}>(flag)) != 0; }}");
        }
        w.Line();
    }

    private static void EmitRecord(CodeWriter w, StructDef s, CTypes c)
    {
        var native = c.Name(s);
        w.Doc(s.Doc, "cpp");
        using (w.Block($"struct {s.Name}", ";"))
        {
            foreach (var f in s.Fields)
            {
                var type = f.FixedString != null ? "std::string" : Cpp(f.Type);
                w.Line($"{type} {Member(f)}{{}};{(f.Doc != null ? " // " + f.Doc : "")}");
            }
            w.Line();
            using (w.Block($"static {s.Name} fromNative(const {native}& n)"))
            {
                w.Line($"{s.Name} r;");
                foreach (var f in s.Fields)
                {
                    var cn = Naming.SafeC(Naming.Snake(f.Name));
                    var expr = f.FixedString != null ? $"detail::readFixed(n.{cn}, sizeof(n.{cn}))"
                        : f.Type is EnumType e ? $"static_cast<{e.Def.Name}>(n.{cn})"
                        : $"n.{cn}";
                    w.Line($"r.{Member(f)} = {expr};");
                }
                w.Line("return r;");
            }
            w.Line();
            using (w.Block($"void toNative({native}& n) const"))
            {
                foreach (var f in s.Fields)
                {
                    var cn = Naming.SafeC(Naming.Snake(f.Name));
                    if (f.FixedString != null) w.Line($"detail::writeFixed({Member(f)}, n.{cn}, sizeof(n.{cn}));");
                    else if (f.Type is EnumType) w.Line($"n.{cn} = static_cast<{c.Type(f.Type)}>({Member(f)});");
                    else w.Line($"n.{cn} = {Member(f)};");
                }
            }
        }
        w.Line();
    }

    private static string Member(FieldDef f) => Naming.SafeC(Naming.Camel(f.Name));
    private static string Arg(ParamDef p) => Naming.SafeC(Naming.Camel(p.Name));

    /// <summary>C++ parameter declarations (one per contract parameter).</summary>
    private static string Params(NMethod m, bool hostImpl)
    {
        var list = new List<string>();
        foreach (var p in m.Params)
        {
            if (p.Source == null || p.Kind == NKind.SpanCount) continue;
            var name = Arg(p.Source);
            list.Add(p.Kind switch
            {
                NKind.Value => $"{Cpp(p.Type)} {name}",
                NKind.Bool => $"bool {name}",
                NKind.String => hostImpl ? $"std::string_view {name}" : $"const std::string& {name}",
                NKind.StructIn or NKind.RecordIn => $"const {Cpp(p.Type)}& {name}",
                NKind.StructRef or NKind.StructOut or NKind.PrimRef or NKind.PrimOut => $"{Cpp(p.Type)}& {name}",
                NKind.SpanData => p.ReadOnly ? $"std::span<const {Cpp(p.Type)}> {name}" : $"std::span<{Cpp(p.Type)}> {name}",
                _ => throw new InvalidOperationException(),
            });
        }
        return string.Join(", ", list);
    }

    private static string ReturnCpp(MethodDef m) => m.Return is PrimType { Kind: Prim.Void } ? "void" : Cpp(m.Return);

    // ---- [ManagedApi]: proxy that calls into C# -------------------------------

    private static void EmitProxy(CodeWriter w, InterfaceDef iface, CTypes c, AbiModel model)
    {
        var cls = Naming.Pascal(iface.ApiName) + "Api";
        var raw = c.Name(iface);
        var methods = Lowering.Lower(iface);
        var M = c.Macro;

        w.Line($"// {(iface.Doc != null ? iface.Doc + " " : "")}Owns the managed instance: the destructor calls destroy.");
        using (w.Block($"class {cls}", ";"))
        {
            w.Outdent(); w.Line("public:"); w.Indent();
            using (w.Block($"explicit {cls}(const {raw}& api) noexcept"))
                w.Line("std::memcpy(&api_, &api, std::min<size_t>(api.struct_size, sizeof(api_)));");
            w.Line($"~{cls}() {{ if (api_.destroy != nullptr) api_.destroy(api_.self); }}");
            w.Line($"{cls}(const {cls}&) = delete;");
            w.Line($"{cls}& operator=(const {cls}&) = delete;");
            w.Line();
            w.Line("// Name of the first required member the implementation did not provide, or nullptr.");
            using (w.Block($"static const char* findMissing(const {raw}& api) noexcept"))
            {
                w.Line($"{raw} a{{}};");
                w.Line("std::memcpy(&a, &api, std::min<size_t>(api.struct_size, sizeof(a)));");
                foreach (var m in methods.Where(m => !m.Method.Optional))
                    w.Line($"if (a.{m.CName} == nullptr) return \"{m.CName}\";");
                w.Line("return nullptr;");
            }
            w.Line();
            w.Line($"const {raw}& raw() const noexcept {{ return api_; }}");
            foreach (var m in methods.Where(m => m.Method.Optional))
                w.Line($"bool supports{m.Method.Name}() const noexcept {{ return api_.{m.CName} != nullptr; }}");

            foreach (var m in methods.Where(m => !m.IsDestroy))
            {
                w.Line();
                var tag = m.Method.Thread == ThreadKind.Audio ? "[audio]" : "[main]";
                w.Line($"// {tag}{(m.Method.Doc != null ? " " + m.Method.Doc : "")}");
                EmitProxyMethod(w, m, c, M);
            }

            w.Line();
            w.Outdent(); w.Line("private:"); w.Indent();
            w.Line($"{raw} api_{{}};");
        }
        w.Line();
    }

    private static void EmitProxyMethod(CodeWriter w, NMethod m, CTypes c, string M)
    {
        var md = m.Method;
        var ret = md.Return;
        bool isVoid = ret is PrimType { Kind: Prim.Void };
        bool isArray = ret is ArrayType;
        var resultType = isVoid ? "Status" : $"Result<{Cpp(ret)}>";
        var noexc = md.Thread == ThreadKind.Audio ? " noexcept" : "";

        using (w.Block($"{resultType} {Naming.Camel(md.Name)}({Params(m, hostImpl: false)}) const{noexc}"))
        {
            if (md.Optional) w.Line($"if (api_.{m.CName} == nullptr) return {resultType}{{{M}_NOT_SUPPORTED}};");

            var args = new List<string> { "api_.self" };
            string? outConv = null;
            foreach (var p in m.Params)
            {
                var name = p.Source != null ? Arg(p.Source) : "";
                switch (p.Kind)
                {
                    case NKind.Value:
                        args.Add(p.Type is EnumType ? $"static_cast<{c.Type(p.Type)}>({name})"
                            : p.Type is PointerType ? $"reinterpret_cast<{c.Type(p.Type)}>({name})" : name);
                        break;
                    case NKind.Bool: args.Add($"static_cast<uint8_t>({name} ? 1 : 0)"); break;
                    case NKind.String: args.Add($"{name}.c_str()"); break;
                    case NKind.StructIn or NKind.StructRef or NKind.StructOut: args.Add($"&{name}"); break;
                    case NKind.PrimRef or NKind.PrimOut:
                        args.Add(p.Type is EnumType ? $"reinterpret_cast<{c.Type(p.Type)}*>(&{name})" : $"&{name}"); break;
                    case NKind.RecordIn:
                        w.Line($"{c.Type(p.Type)} {name}Native{{}};");
                        w.Line($"{name}.toNative({name}Native);");
                        args.Add($"&{name}Native");
                        break;
                    case NKind.SpanData: args.Add($"reinterpret_cast<{c.ParamType(p)}>({name}.data())"); break;
                    case NKind.SpanCount: args.Add($"static_cast<uint32_t>({Arg(p.Source!)}.size())"); break;
                    case NKind.RetValue:
                        w.Line($"{c.Type(p.Type)} out{{}};");
                        args.Add("&out");
                        outConv = p.Type is EnumType or PointerType ? $"{(p.Type is EnumType ? "static_cast" : "reinterpret_cast")}<{Cpp(p.Type)}>(out)" : "out";
                        break;
                    case NKind.RetBool: w.Line("uint8_t out = 0;"); args.Add("&out"); outConv = "out != 0"; break;
                    case NKind.RetRecord:
                        w.Line($"{c.Type(p.Type)} out{{}};");
                        args.Add("&out");
                        outConv = $"{Cpp(p.Type)}::fromNative(out)";
                        break;
                }
            }

            if (isArray)
            {
                var elem = ((ArrayType)ret).Element;
                var call = string.Join(", ", args);
                w.Line("uint32_t count = 0;");
                w.Line($"{resultType} r;");
                w.Line($"r.code = api_.{m.CName}({call}, nullptr, 0, &count);");
                w.Line($"if (r.code != {M}_OK) return r;");
                w.Line("r.value.resize(count);");
                w.Line($"r.code = api_.{m.CName}({call}, reinterpret_cast<{c.Type(elem)}*>(r.value.data()), count, &count);");
                w.Line($"if (r.code == {M}_OK) r.value.resize(count);");
                w.Line("return r;");
            }
            else if (isVoid)
            {
                w.Line($"return Status{{api_.{m.CName}({string.Join(", ", args)})}};");
            }
            else
            {
                w.Line($"{resultType} r;");
                w.Line($"r.code = api_.{m.CName}({string.Join(", ", args)});");
                w.Line($"if (r.code == {M}_OK) r.value = {outConv};");
                w.Line("return r;");
            }
        }
    }

    // ---- [NativeApi]: abstract class implemented in C++, called from C# -------------

    private static void EmitNativeInterface(CodeWriter w, InterfaceDef iface, CTypes c, AbiModel model)
    {
        var cls = Naming.Pascal(iface.ApiName) + "Api";
        var raw = c.Name(iface);
        var methods = Lowering.Lower(iface);
        var M = c.Macro;

        w.Line($"// {(iface.Doc != null ? iface.Doc + " " : "")}Implement this and pass make{cls}(impl) to the managed side.");
        w.Line("// Methods report failure by throwing; NotSupported maps to NOT_SUPPORTED, anything else to EXCEPTION.");
        using (w.Block($"class {cls}", ";"))
        {
            w.Outdent(); w.Line("public:"); w.Indent();
            w.Line($"virtual ~{cls}() = default;");
            foreach (var m in methods)
            {
                w.Line();
                var tag = m.Method.Thread == ThreadKind.Audio ? "[audio]" : "[main]";
                w.Line($"// {tag}{(m.Method.Optional ? " [optional]" : "")}{(m.Method.Doc != null ? " " + m.Method.Doc : "")}");
                var decl = $"virtual {ReturnCpp(m.Method)} {Naming.Camel(m.Method.Name)}({Params(m, hostImpl: true)})";
                if (!m.Method.Optional)
                {
                    w.Line(decl + " = 0;");
                    continue;
                }
                // The default ignores its parameters (named for the overrides' sake; (void) keeps warnings away).
                var unused = string.Concat(m.Params.Where(p => p.Source != null && p.Kind != NKind.SpanCount)
                                                   .Select(p => $"(void){Arg(p.Source!)}; "));
                w.Line(decl + " { " + unused + "throw NotSupported{}; }");
            }
        }
        w.Line();

        using (w.Block("namespace detail"))
        {
            using (w.Block($"struct {cls}Thunks", ";"))
            {
                foreach (var m in methods) EmitThunk(w, m, c, cls, iface, M);
            }
        }
        w.Line();

        using (w.Block($"inline {raw} make{cls}({cls}& impl) noexcept"))
        {
            w.Line($"{raw} api{{}};");
            w.Line($"api.struct_size = sizeof({raw});");
            w.Line($"api.abi_version = {M}_ABI_VERSION;");
            w.Line($"api.ctx = &impl;");
            foreach (var m in methods)
                w.Line($"api.{m.CName} = &detail::{cls}Thunks::{Naming.Camel(m.Method.Name)};");
            w.Line("return api;");
        }
        w.Line();
    }

    private static void EmitThunk(CodeWriter w, NMethod m, CTypes c, string cls, InterfaceDef iface, string M)
    {
        var md = m.Method;
        using (w.Block($"static {c.Prefix}_result {M}_CALL {Naming.Camel(md.Name)}({c.Signature(iface, m)}) noexcept"))
        {
            using (w.Block("try"))
            {
                foreach (var p in m.Params.Where(p => Lowering.IsRequiredPointer(p.Kind)))
                    w.Line($"if ({p.CName} == nullptr) return {M}_INVALID_ARGUMENT;");
                foreach (var p in m.Params.Where(p => p.Kind == NKind.SpanData))
                    w.Line($"if ({p.CName} == nullptr && {p.CName}_count != 0) return {M}_INVALID_ARGUMENT;");
                w.Line($"auto& impl = *static_cast<{cls}*>(ctx);");

                var args = new List<string>();
                foreach (var p in m.Params)
                {
                    switch (p.Kind)
                    {
                        case NKind.Value:
                            args.Add(p.Type is EnumType ? $"static_cast<{Cpp(p.Type)}>({p.CName})"
                                : p.Type is PointerType ? $"reinterpret_cast<{Cpp(p.Type)}>({p.CName})" : p.CName);
                            break;
                        case NKind.Bool: args.Add($"{p.CName} != 0"); break;
                        case NKind.String: args.Add($"std::string_view({p.CName} != nullptr ? {p.CName} : \"\")"); break;
                        case NKind.StructIn or NKind.StructRef or NKind.StructOut: args.Add($"*{p.CName}"); break;
                        case NKind.PrimRef or NKind.PrimOut:
                            args.Add(p.Type is EnumType ? $"*reinterpret_cast<{Cpp(p.Type)}*>({p.CName})" : $"*{p.CName}"); break;
                        case NKind.RecordIn: args.Add($"{Cpp(p.Type)}::fromNative(*{p.CName})"); break;
                        case NKind.SpanData:
                            var elem = p.ReadOnly ? $"const {Cpp(p.Type)}" : Cpp(p.Type);
                            args.Add($"std::span<{elem}>(reinterpret_cast<{elem}*>({p.CName}), {p.CName}_count)");
                            break;
                    }
                }
                var call = $"impl.{Naming.Camel(md.Name)}({string.Join(", ", args)})";
                var ret = m.Params.FirstOrDefault(p => p.Kind is NKind.RetValue or NKind.RetBool or NKind.RetRecord or NKind.ArrBuffer);
                switch (ret?.Kind)
                {
                    case null: w.Line($"{call};"); break;
                    case NKind.RetValue:
                        w.Line(ret.Type is EnumType ? $"*out_value = static_cast<{c.Type(ret.Type)}>({call});"
                            : ret.Type is PointerType ? $"*out_value = reinterpret_cast<{c.Type(ret.Type)}>({call});"
                            : $"*out_value = {call};");
                        break;
                    case NKind.RetBool: w.Line($"*out_value = ({call}) ? 1 : 0;"); break;
                    case NKind.RetRecord: w.Line($"{call}.toNative(*out_value);"); break;
                    case NKind.ArrBuffer:
                        w.Line($"const auto values = {call};");
                        w.Line("*out_count = static_cast<uint32_t>(values.size());");
                        w.Line($"if (buffer == nullptr) return {M}_OK;");
                        w.Line($"if (capacity < values.size()) return {M}_BUFFER_TOO_SMALL;");
                        w.Line("if (!values.empty()) std::memcpy(buffer, values.data(), values.size() * sizeof(*buffer));");
                        break;
                }
                w.Line($"return {M}_OK;");
            }
            w.Line($"catch (const NotSupported&) {{ return {M}_NOT_SUPPORTED; }}");
            w.Line($"catch (...) {{ return {M}_EXCEPTION; }}");
        }
    }
}
