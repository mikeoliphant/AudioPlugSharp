namespace AbiGen;

/// <summary>
/// Emits the C# interop layer: result codes, record mirrors and marshalling, vtable structs, layout
/// verification, [UnmanagedCallersOnly] thunks for [ManagedApi] interfaces and proxies for [NativeApi] ones.
/// Hand-written support types it relies on: AbiUtf8, AbiCallException, IAbiErrorHandler.
/// </summary>
public static class CSharpEmitter
{
    public static Dictionary<string, string> Emit(AbiModel model)
    {
        var files = new Dictionary<string, string> { ["Abi.g.cs"] = EmitCommon(model) };
        foreach (var iface in model.Interfaces)
        {
            var name = Naming.Pascal(iface.ApiName) + (iface.Direction == ApiDirection.Managed ? "ApiThunks" : "ApiProxy");
            files[name + ".g.cs"] = iface.Direction == ApiDirection.Managed ? EmitThunks(model, iface) : EmitProxy(model, iface);
        }
        return files;
    }

    private static CodeWriter Begin(AbiModel model)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated>");
        w.Line($"// Generated by AbiGen from {model.ContractAssembly}. Do not edit; change the contract instead.");
        w.Line("// </auto-generated>");
        w.Line("#nullable enable");
        w.Line("using System;");
        w.Line("using System.Runtime.CompilerServices;");
        w.Line("using System.Runtime.InteropServices;");
        w.Line();
        w.Line($"namespace {model.CSharpNamespace};");
        w.Line();
        return w;
    }

    // ---- types ----------------------------------------------------------------

    private static string Prim(Prim p, bool managed) => p switch
    {
        AbiGen.Prim.Void => "void",
        AbiGen.Prim.Bool => managed ? "bool" : "byte",
        AbiGen.Prim.I8 => "sbyte",
        AbiGen.Prim.U8 => "byte",
        AbiGen.Prim.I16 => "short",
        AbiGen.Prim.U16 => "ushort",
        AbiGen.Prim.I32 => "int",
        AbiGen.Prim.U32 => "uint",
        AbiGen.Prim.I64 => "long",
        AbiGen.Prim.U64 => "ulong",
        AbiGen.Prim.F32 => "float",
        AbiGen.Prim.F64 => "double",
        AbiGen.Prim.IntPtr => "nint",
        AbiGen.Prim.UIntPtr => "nuint",
        _ => throw new ArgumentOutOfRangeException(nameof(p)),
    };

    /// <summary>Managed (contract) type, as used in the interface signatures.</summary>
    private static string Managed(TypeRef t) => t switch
    {
        PrimType p => Prim(p.Kind, managed: true),
        EnumType e => "global::" + e.Def.FullName,
        StructType s => "global::" + s.Def.FullName,
        PointerType p => Native(p.Element) + "*",
        StringType => "string",
        SpanType s => $"{(s.ReadOnly ? "ReadOnlySpan" : "Span")}<{Managed(s.Element)}>",
        ArrayType a => Managed(a.Element) + "[]",
        _ => throw new InvalidOperationException(),
    };

    /// <summary>Blittable type as it appears in native signatures and structs.</summary>
    private static string Native(TypeRef t) => t switch
    {
        PrimType p => Prim(p.Kind, managed: false),
        EnumType e => "global::" + e.Def.FullName,
        StructType { Def.IsRecord: true } s => s.Def.Name + "Native",
        StructType s => "global::" + s.Def.FullName,
        PointerType p => Native(p.Element) + "*",
        _ => throw new InvalidOperationException($"no native C# type for {t}"),
    };

    private static string ParamNative(NParam p) => p.Kind switch
    {
        NKind.Value => Native(p.Type),
        NKind.Bool => "byte",
        NKind.String => "byte*",
        NKind.StructIn or NKind.StructRef or NKind.StructOut or NKind.PrimRef or NKind.PrimOut => Native(p.Type) + "*",
        NKind.RecordIn or NKind.RetRecord => Native(p.Type) + "*",
        NKind.SpanData or NKind.ArrBuffer => Native(p.Type) + "*",
        NKind.SpanCount or NKind.ArrCapacity => "uint",
        NKind.RetValue => Native(p.Type) + "*",
        NKind.RetBool => "byte*",
        NKind.ArrCount => "uint*",
        _ => throw new ArgumentOutOfRangeException(),
    };

    private static string FnPointerType(NMethod m) =>
        $"delegate* unmanaged<{string.Join(", ", new[] { "void*" }.Concat(m.Params.Select(ParamNative)).Append(m.IsDestroy ? "void" : "int"))}>";

    private static string VTableName(InterfaceDef i) => Naming.Pascal(i.ApiName) + "ApiVTable";

    // ---- common file ------------------------------------------------------------

    private static string EmitCommon(AbiModel model)
    {
        var c = new CTypes(model);
        var w = Begin(model);

        using (w.Block("internal static class AbiInfo"))
        {
            w.Line($"public const uint Version = {model.Version};");
        }
        w.Line();

        using (w.Block("internal static class AbiResult"))
        {
            foreach (var (name, value, doc) in CEmitter.ResultCodes)
            {
                w.Doc(doc, "cs");
                w.Line($"public const int {Naming.Pascal(name.ToLowerInvariant())} = {value};");
            }
            w.Line();
            w.Line("public static void ThrowIfFailed(int code, string member)");
            w.Line("{");
            w.Line("    if (code != Ok) throw new AbiCallException(member, code);");
            w.Line("}");
        }
        w.Line();

        foreach (var s in model.Structs.Where(s => s.IsRecord))
        {
            w.Line($"/// <summary>Native mirror of <see cref=\"global::{s.FullName}\"/> ({c.Name(s)}).</summary>");
            w.Line("[StructLayout(LayoutKind.Sequential)]");
            using (w.Block($"internal unsafe struct {s.Name}Native"))
            {
                foreach (var f in s.Fields)
                    w.Line(f.FixedString is { } len ? $"public fixed byte {f.Name}[{len}];" : $"public {Native(f.Type)} {f.Name};");
            }
            w.Line();
        }

        using (w.Block("internal static unsafe class AbiMarshal"))
        {
            foreach (var s in model.Structs.Where(s => s.IsRecord))
            {
                var t = "global::" + s.FullName;
                using (w.Block($"public static void ToNative(in {t} value, {s.Name}Native* native)"))
                {
                    foreach (var f in s.Fields)
                        w.Line(f.FixedString is { } len
                            ? $"AbiUtf8.WriteFixed(value.{f.Name}, native->{f.Name}, {len});"
                            : $"native->{f.Name} = value.{f.Name};");
                }
                w.Line();
                using (w.Block($"public static {t} FromNative({s.Name}Native* native)"))
                {
                    w.Line($"var value = new {t}();");
                    foreach (var f in s.Fields)
                        w.Line(f.FixedString is { } len
                            ? $"value.{f.Name} = AbiUtf8.ReadFixed(native->{f.Name}, {len});"
                            : $"value.{f.Name} = native->{f.Name};");
                    w.Line("return value;");
                }
                w.Line();
            }
        }
        w.Line();

        foreach (var iface in model.Interfaces)
        {
            var methods = Lowering.Lower(iface);
            w.Line($"/// <summary>Mirror of {c.Name(iface)}.</summary>");
            w.Line("[StructLayout(LayoutKind.Sequential)]");
            using (w.Block($"internal unsafe struct {VTableName(iface)}"))
            {
                w.Line("public uint StructSize;");
                w.Line("public uint AbiVersion;");
                w.Line($"public void* {(iface.Direction == ApiDirection.Managed ? "Self" : "Ctx")};");
                foreach (var m in methods)
                    w.Line($"public {FnPointerType(m)} {m.Method.Name};");
            }
            w.Line();
        }

        EmitLayoutVerify(w, model, c);
        return w.ToString();
    }

    private static void EmitLayoutVerify(CodeWriter w, AbiModel model, CTypes c)
    {
        w.Line("/// <summary>Checks the C# layouts against the generator's C layout. Returns an error message, or null.</summary>");
        using (w.Block("internal static unsafe class AbiLayout"))
        {
            using (w.Block("public static string? Verify()"))
            {
                w.Line("if (sizeof(void*) != 8) return \"the ABI requires a 64-bit process\";");
                foreach (var s in model.Structs)
                {
                    var type = s.IsRecord ? s.Name + "Native" : "global::" + s.FullName;
                    var layout = Layout.Compute(s);
                    var fields = s.Fields.Zip(layout.Fields, (f, l) => (Expr: f.FixedString != null ? $"(byte*)v.{f.Name}" : $"(byte*)&v.{f.Name}", l.Offset, f.Name));
                    EmitVerifyType(w, type, c.Name(s), layout.Size, fields);
                }
                foreach (var iface in model.Interfaces)
                {
                    var methods = Lowering.Lower(iface);
                    var layout = Layout.VTable(methods, c.SelfName(iface));
                    var names = new[] { "StructSize", "AbiVersion", iface.Direction == ApiDirection.Managed ? "Self" : "Ctx" }
                        .Concat(methods.Select(m => m.Method.Name)).ToList();
                    var fields = names.Zip(layout.Fields, (n, l) => (Expr: $"(byte*)&v.{n}", l.Offset, Name: n));
                    EmitVerifyType(w, VTableName(iface), c.Name(iface), layout.Size, fields);
                }
                w.Line("return null;");
            }
        }
    }

    private static void EmitVerifyType(CodeWriter w, string type, string cName, int size,
        IEnumerable<(string Expr, int Offset, string Name)> fields)
    {
        w.Line($"if (sizeof({type}) != {size}) return $\"{cName}: size {{sizeof({type})}}, expected {size}\";");
        using (w.Block(""))
        {
            w.Line($"{type} v = default;");
            foreach (var (expr, offset, name) in fields)
                w.Line($"if ({expr} - (byte*)&v != {offset}) return \"{cName}.{name}: offset mismatch (expected {offset})\";");
        }
    }

    // ---- [ManagedApi]: thunks called by native code -------------------------------

    private static string EmitThunks(AbiModel model, InterfaceDef iface)
    {
        var w = Begin(model);
        var cls = Naming.Pascal(iface.ApiName) + "ApiThunks";
        var vt = VTableName(iface);
        var contract = "global::" + iface.FullName;
        var methods = Lowering.Lower(iface);

        w.Line($"/// <summary>[UnmanagedCallersOnly] implementation of {new CTypes(model).Name(iface)} over <see cref=\"{contract}\"/>.</summary>");
        using (w.Block($"internal static unsafe partial class {cls}"))
        {
            w.Line("/// <summary>Fills the vtable. <paramref name=\"self\"/> is a GCHandle to the implementation (freed by Destroy).</summary>");
            using (w.Block($"public static void Fill({vt}* api, nint self)"))
            {
                w.Line("*api = default;");
                w.Line($"api->StructSize = (uint)sizeof({vt});");
                w.Line("api->AbiVersion = AbiInfo.Version;");
                w.Line("api->Self = (void*)self;");
                foreach (var m in methods) w.Line($"api->{m.Method.Name} = &{m.Method.Name};");
            }
            w.Line();
            w.Line("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
            w.Line($"private static {contract} Get(void* self) => Unsafe.As<{contract}>(GCHandle.FromIntPtr((nint)self).Target!);");
            w.Line();
            using (w.Block("private static int Fail(void* self, string member, Exception exception)"))
            {
                w.Line("try { (GCHandle.FromIntPtr((nint)self).Target as IAbiErrorHandler)?.OnAbiException(member, exception); }");
                w.Line("catch { /* nothing more we can do */ }");
                w.Line("return AbiResult.Exception;");
            }

            foreach (var m in methods)
            {
                w.Line();
                if (m.IsDestroy) EmitDestroyThunk(w);
                else EmitThunk(w, m);
            }
        }
        return w.ToString();
    }

    private static void EmitDestroyThunk(CodeWriter w)
    {
        w.Line("[UnmanagedCallersOnly]");
        using (w.Block("internal static void Destroy(void* self)"))
        {
            using (w.Block("try"))
            {
                w.Line("var handle = GCHandle.FromIntPtr((nint)self);");
                w.Line("var target = handle.Target;");
                w.Line("try { (target as IDisposable)?.Dispose(); }");
                w.Line("finally { handle.Free(); }");
            }
            using (w.Block("catch (Exception e)"))
                w.Line("AbiUtf8.ReportUnhandled(\"Destroy\", e);");
        }
    }

    private static void EmitThunk(CodeWriter w, NMethod m)
    {
        var md = m.Method;
        var sig = string.Join(", ", new[] { "void* self" }.Concat(m.Params.Select(p => $"{ParamNative(p)} {p.CsName}")));
        w.Line($"/// <summary>[{(md.Thread == ThreadKind.Audio ? "audio" : "main")}] {System.Security.SecurityElement.Escape(md.Doc ?? md.Name)}</summary>");
        w.Line("[UnmanagedCallersOnly]");
        using (w.Block($"internal static int {md.Name}({sig})"))
        {
            using (w.Block("try"))
            {
                foreach (var p in m.Params.Where(p => Lowering.IsRequiredPointer(p.Kind)))
                    w.Line($"if ({p.CsName} == null) return AbiResult.InvalidArgument;");
                foreach (var p in m.Params.Where(p => p.Kind == NKind.SpanData))
                    w.Line($"if ({p.CsName} == null && {p.CsName}Count != 0) return AbiResult.InvalidArgument;");

                var args = new List<string>();
                foreach (var p in m.Params)
                {
                    switch (p.Kind)
                    {
                        case NKind.Value: args.Add(p.CsName); break;
                        case NKind.Bool: args.Add($"{p.CsName} != 0"); break;
                        case NKind.String: args.Add($"AbiUtf8.FromNative({p.CsName})"); break;
                        case NKind.StructIn: args.Add($"in *{p.CsName}"); break;
                        case NKind.StructRef or NKind.PrimRef: args.Add($"ref *{p.CsName}"); break;
                        case NKind.StructOut or NKind.PrimOut: args.Add($"out *{p.CsName}"); break;
                        case NKind.RecordIn: args.Add($"AbiMarshal.FromNative({p.CsName})"); break;
                        case NKind.SpanData:
                            args.Add($"new {(p.ReadOnly ? "ReadOnlySpan" : "Span")}<{Native(p.Type)}>({p.CsName}, checked((int){p.CsName}Count))");
                            break;
                    }
                }
                var call = $"Get(self).{md.Name}({string.Join(", ", args)})";
                var ret = m.Params.FirstOrDefault(p => p.Kind is NKind.RetValue or NKind.RetBool or NKind.RetRecord or NKind.ArrBuffer);
                switch (ret?.Kind)
                {
                    case null: w.Line($"{call};"); break;
                    case NKind.RetValue: w.Line($"*outValue = {call};"); break;
                    case NKind.RetBool: w.Line($"*outValue = {call} ? (byte)1 : (byte)0;"); break;
                    case NKind.RetRecord:
                        w.Line($"var result = {call};");
                        w.Line("AbiMarshal.ToNative(in result, outValue);");
                        break;
                    case NKind.ArrBuffer:
                        var elem = Native(ret.Type);
                        w.Line($"var result = {call} ?? Array.Empty<{elem}>();");
                        w.Line("*outCount = (uint)result.Length;");
                        w.Line("if (buffer == null) return AbiResult.Ok;");
                        w.Line("if (capacity < (uint)result.Length) return AbiResult.BufferTooSmall;");
                        w.Line($"result.AsSpan().CopyTo(new Span<{elem}>(buffer, result.Length));");
                        break;
                }
                w.Line("return AbiResult.Ok;");
            }
            w.Line("catch (ArgumentException) { return AbiResult.InvalidArgument; }");
            w.Line("catch (NotSupportedException) { return AbiResult.NotSupported; }");
            w.Line($"catch (Exception e) {{ return Fail(self, \"{md.Name}\", e); }}");
        }
    }

    // ---- [NativeApi]: proxy that calls native code ----------------------------------

    private static string EmitProxy(AbiModel model, InterfaceDef iface)
    {
        var w = Begin(model);
        var cls = Naming.Pascal(iface.ApiName) + "ApiProxy";
        var vt = VTableName(iface);
        var contract = "global::" + iface.FullName;
        var methods = Lowering.Lower(iface);

        w.Line($"/// <summary>Implements <see cref=\"{contract}\"/> by calling the native {new CTypes(model).Name(iface)}.</summary>");
        using (w.Block($"internal sealed unsafe partial class {cls} : {contract}"))
        {
            w.Line($"private readonly {vt} _api;");
            w.Line();
            w.Line("/// <summary>Copies the vtable; members beyond the native struct_size read as null.</summary>");
            using (w.Block($"public {cls}({vt}* api)"))
            {
                w.Line("_api = Copy(api);");
            }
            w.Line();
            using (w.Block($"private static {vt} Copy({vt}* api)"))
            {
                w.Line($"{vt} copy = default;");
                w.Line($"uint size = Math.Min(api->StructSize, (uint)sizeof({vt}));");
                w.Line($"Buffer.MemoryCopy(api, &copy, sizeof({vt}), size);");
                w.Line("return copy;");
            }
            w.Line();
            w.Line("/// <summary>Name of the first required member the native side did not provide, or null.</summary>");
            using (w.Block($"public static string? FindMissing({vt}* api)"))
            {
                w.Line("var a = Copy(api);");
                foreach (var m in methods.Where(m => !m.Method.Optional))
                    w.Line($"if (a.{m.Method.Name} == null) return \"{m.CName}\";");
                w.Line("return null;");
            }
            w.Line();
            w.Line("public uint AbiVersion => _api.AbiVersion;");
            foreach (var m in methods.Where(m => m.Method.Optional))
                w.Line($"public bool Supports{m.Method.Name} => _api.{m.Method.Name} != null;");

            foreach (var m in methods)
            {
                w.Line();
                EmitProxyMethod(w, m);
            }
        }
        return w.ToString();
    }

    private static void EmitProxyMethod(CodeWriter w, NMethod m)
    {
        var md = m.Method;
        var ret = md.Return;
        bool isVoid = ret is PrimType { Kind: AbiGen.Prim.Void };
        var retType = isVoid ? "void" : Managed(ret);
        var decl = string.Join(", ", md.Params.Select(p => $"{ModKeyword(p.Mod)}{Managed(p.Type)} {p.Name}"));

        w.Line($"/// <summary>[{(md.Thread == ThreadKind.Audio ? "audio" : "main")}] {System.Security.SecurityElement.Escape(md.Doc ?? md.Name)}</summary>");
        using (w.Block($"public {retType} {md.Name}({decl})"))
        {
            foreach (var p in md.Params.Where(p => p.Mod == ParamMod.Out)) w.Line($"{p.Name} = default;");
            w.Line($"var __fn = _api.{md.Name};");
            if (md.Optional)
                w.Line($"if (__fn == null) return{(isVoid ? "" : ret is ArrayType a ? $" Array.Empty<{Managed(a.Element)}>()" : " default")};");
            else
                w.Line($"if (__fn == null) throw new AbiCallException(\"{md.Name}\", AbiResult.NotSupported);");

            var args = new List<string> { "_api.Ctx" };
            var fixeds = new List<string>();
            string? resultExpr = null;
            foreach (var p in m.Params)
            {
                var n = p.CsName;
                switch (p.Kind)
                {
                    case NKind.Value: args.Add(n); break;
                    case NKind.Bool: args.Add($"(byte)({n} ? 1 : 0)"); break;
                    case NKind.String:
                        w.Line($"byte[] {n}__u8 = AbiUtf8.ToNullTerminated({n});");
                        fixeds.Add($"fixed (byte* {n}__p = {n}__u8)");
                        args.Add($"{n}__p");
                        break;
                    case NKind.StructIn or NKind.StructRef or NKind.StructOut or NKind.PrimRef or NKind.PrimOut:
                        fixeds.Add($"fixed ({Native(p.Type)}* {n}__p = &{n})");
                        args.Add($"{n}__p");
                        break;
                    case NKind.RecordIn:
                        w.Line($"{Native(p.Type)} {n}__n;");
                        w.Line($"AbiMarshal.ToNative(in {n}, &{n}__n);");
                        args.Add($"&{n}__n");
                        break;
                    case NKind.SpanData:
                        fixeds.Add($"fixed ({Native(p.Type)}* {n}__p = {n})");
                        args.Add($"{n}__p");
                        break;
                    case NKind.SpanCount: args.Add($"(uint){p.Source!.Name}.Length"); break;
                    case NKind.RetValue:
                        w.Line($"{Native(p.Type)} __result = default;");
                        args.Add("&__result");
                        resultExpr = "__result";
                        break;
                    case NKind.RetBool:
                        w.Line("byte __result = 0;");
                        args.Add("&__result");
                        resultExpr = "__result != 0";
                        break;
                    case NKind.RetRecord:
                        w.Line($"{Native(p.Type)} __result;");
                        args.Add("&__result");
                        resultExpr = "AbiMarshal.FromNative(&__result)";
                        break;
                }
            }

            foreach (var f in fixeds) { w.Line(f); }
            using (w.Block(""))
            {
                if (ret is ArrayType arr)
                {
                    var elem = Native(arr.Element);
                    var call = string.Join(", ", args);
                    w.Line("uint __count = 0;");
                    w.Line($"AbiResult.ThrowIfFailed(__fn({call}, null, 0, &__count), \"{md.Name}\");");
                    w.Line($"var __values = new {elem}[__count];");
                    w.Line($"fixed ({elem}* __buffer = __values)");
                    w.Line($"    AbiResult.ThrowIfFailed(__fn({call}, __buffer, __count, &__count), \"{md.Name}\");");
                    w.Line("if (__count < __values.Length) Array.Resize(ref __values, (int)__count);");
                    w.Line("return __values;");
                }
                else
                {
                    w.Line($"AbiResult.ThrowIfFailed(__fn({string.Join(", ", args)}), \"{md.Name}\");");
                    if (resultExpr != null) w.Line($"return {resultExpr};");
                }
            }
        }
    }

    private static string ModKeyword(ParamMod m) => m switch
    {
        ParamMod.In => "in ",
        ParamMod.Ref => "ref ",
        ParamMod.Out => "out ",
        _ => "",
    };
}
