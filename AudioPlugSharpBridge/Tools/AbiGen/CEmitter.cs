namespace AbiGen;

/// <summary>Emits the C header: result codes, enums, structs, record mirrors, vtables and layout checks.</summary>
public static class CEmitter
{
    public static readonly (string Name, int Value, string Doc)[] ResultCodes =
    [
        ("OK", 0, "Success."),
        ("ERROR", -1, "Unspecified failure."),
        ("INVALID_ARGUMENT", -2, "An argument was null or out of range."),
        ("BUFFER_TOO_SMALL", -3, "The caller's buffer is too small; query the size first."),
        ("EXCEPTION", -4, "The implementation threw; details were reported through the error handler."),
        ("ABI_MISMATCH", -5, "The two sides were generated from incompatible contracts."),
        ("NOT_SUPPORTED", -6, "The implementation does not provide this (optional) member."),
    ];

    public static string Emit(AbiModel model)
    {
        var c = new CTypes(model);
        var M = c.Macro;
        var w = new CodeWriter();
        var guard = $"{M}_GENERATED_ABI_H";

        w.Line($"/* Generated by AbiGen from {model.ContractAssembly}. Do not edit; change the contract instead. */");
        w.Line($"#ifndef {guard}");
        w.Line($"#define {guard}");
        w.Line();
        w.Line("#include <stddef.h>");
        w.Line("#include <stdint.h>");
        w.Line();
        w.Line("#ifdef __cplusplus");
        w.Line("extern \"C\" {");
        w.Line("#endif");
        w.Line();
        w.Line("/* Matches .NET's platform-default unmanaged calling convention. */");
        w.Line("#if defined(_WIN32) && defined(_M_IX86)");
        w.Line($"#define {M}_CALL __stdcall");
        w.Line("#else");
        w.Line($"#define {M}_CALL");
        w.Line("#endif");
        w.Line();
        w.Line($"#define {M}_ABI_VERSION {model.Version}u");
        w.Line();
        w.Line($"typedef int32_t {c.Prefix}_result;");
        foreach (var (name, value, doc) in ResultCodes)
            w.Line($"#define {M}_{name} (({c.Prefix}_result){value}) /* {doc} */");
        w.Line();

        foreach (var e in model.Enums)
        {
            w.Doc(e.Doc, "c");
            var type = c.Name(e);
            w.Line($"typedef {CTypes.Prim(e.Underlying)} {type};");
            foreach (var m in e.Members)
                w.Line($"#define {c.EnumConst(e, m)} (({type}){Literal(m.Value, e.Underlying)}){(m.Doc != null ? $" /* {m.Doc} */" : "")}");
            w.Line();
        }

        foreach (var s in model.Structs)
        {
            w.Doc(s.Doc, "c");
            w.Line($"typedef struct {c.Name(s)} {{");
            w.Indent();
            foreach (var f in s.Fields)
                w.Line($"{c.FieldDecl(f)};{(f.Doc != null ? $" /* {f.Doc} */" : "")}");
            w.Outdent();
            w.Line($"}} {c.Name(s)};");
            w.Line();
        }

        foreach (var iface in model.Interfaces)
        {
            var methods = Lowering.Lower(iface);
            var who = iface.Direction == ApiDirection.Managed ? "Implemented in C#, called by native code." : "Implemented by native code, called from C#.";
            w.Doc(iface.Doc, "c");
            w.Line($"/* {who} */");
            w.Line($"typedef struct {c.Name(iface)} {{");
            w.Indent();
            w.Line("uint32_t struct_size; /* sizeof this struct as filled in by the implementer; later members may be absent */");
            w.Line($"uint32_t abi_version; /* {M}_ABI_VERSION */");
            w.Line($"void* {c.SelfName(iface)};");
            foreach (var m in methods)
            {
                w.Line();
                var tag = m.Method.Thread == ThreadKind.Audio ? "[audio]" : "[main]";
                var opt = m.Method.Optional ? " [optional]" : "";
                w.Line($"/* {tag}{opt}{(m.Method.Doc != null ? " " + m.Method.Doc : "")} */");
                w.Line($"{c.ReturnType(m)} ({M}_CALL *{m.CName})({c.Signature(iface, m)});");
            }
            w.Outdent();
            w.Line($"}} {c.Name(iface)};");
            w.Line();
        }

        EmitLayoutChecks(w, model, c);

        w.Line("#ifdef __cplusplus");
        w.Line("}");
        w.Line("#endif");
        w.Line();
        w.Line($"#endif /* {guard} */");
        return w.ToString();
    }

    private static void EmitLayoutChecks(CodeWriter w, AbiModel model, CTypes c)
    {
        var M = c.Macro;
        w.Line("/* Layout checks: these values were computed by the generator and are verified on the C# side too. */");
        w.Line("#ifdef __cplusplus");
        w.Line($"#define {M}_ABI_ASSERT(cond, msg) static_assert(cond, msg)");
        w.Line("#else");
        w.Line($"#define {M}_ABI_ASSERT(cond, msg) _Static_assert(cond, msg)");
        w.Line("#endif");
        w.Line($"{M}_ABI_ASSERT(sizeof(void*) == 8, \"the ABI requires a 64-bit target\");");
        foreach (var s in model.Structs)
            EmitChecks(w, M, c.Name(s), Layout.Compute(s));
        foreach (var iface in model.Interfaces)
            EmitChecks(w, M, c.Name(iface), Layout.VTable(Lowering.Lower(iface), c.SelfName(iface)));
        w.Line();
    }

    private static void EmitChecks(CodeWriter w, string M, string type, Layout.StructLayout layout)
    {
        w.Line($"{M}_ABI_ASSERT(sizeof({type}) == {layout.Size}, \"{type} size\");");
        foreach (var f in layout.Fields)
            w.Line($"{M}_ABI_ASSERT(offsetof({type}, {f.CName}) == {f.Offset}, \"{type}.{f.CName} offset\");");
    }

    public static string Literal(long value, Prim underlying)
    {
        bool unsigned = underlying is Prim.U8 or Prim.U16 or Prim.U32 or Prim.U64;
        bool wide = underlying is Prim.I64 or Prim.U64;
        if (value < 0) return $"({value}{(wide ? "ll" : "")})";
        return $"{value}{(unsigned ? "u" : "")}{(wide ? "ll" : "")}";
    }
}
